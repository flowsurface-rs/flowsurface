use std::env;
use std::fs;
use std::path::PathBuf;
use std::process::Command;

fn main() {
    #[cfg(windows)]
    {
        println!("cargo:rerun-if-changed=assets/app-icon/flowsurface.ico");
        println!("cargo:rerun-if-changed=scripts/packaging/windows/flowsurface.manifest");
        println!("cargo:rerun-if-changed=scripts/packaging/windows/flowsurface.rc");
        let macros = [
            format!(
                "APP_VERSION={},{},{},0",
                env!("CARGO_PKG_VERSION_MAJOR"),
                env!("CARGO_PKG_VERSION_MINOR"),
                env!("CARGO_PKG_VERSION_PATCH")
            ),
            format!("APP_VERSION_STRING=\"{}\"", env!("CARGO_PKG_VERSION")),
            format!("APP_NAME=\"{}\"", env!("CARGO_PKG_NAME")),
            format!("APP_DESCRIPTION=\"{}\"", env!("CARGO_PKG_DESCRIPTION")),
            format!(
                "APP_FILE_FLAGS={}",
                u8::from(env::var("PROFILE").as_deref() == Ok("debug"))
            ),
        ];
        embed_resource::compile(
            "scripts/packaging/windows/flowsurface.rc",
            embed_resource::ParamsMacrosAndIncludeDirs(macros, ["scripts/packaging/windows"]),
        )
        .manifest_required()
        .expect("Windows resource compilation failed");
    }
    generate_core_source_manifest().unwrap_or_else(|error| panic!("{error}"));
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-changed=.git/refs");
    println!("cargo:rerun-if-changed=.git/packed-refs");

    let Some(git_sha) = git_output(&["rev-parse", "--short=7", "HEAD"]) else {
        return;
    };

    println!("cargo:rustc-env=FLOWSURFACE_GIT_SHA={git_sha}");

    let pkg_version = env::var("CARGO_PKG_VERSION").unwrap_or_default();
    let is_release_tag = git_head_has_release_tag(&pkg_version);
    println!(
        "cargo:rustc-env=FLOWSURFACE_IS_RELEASE_TAG={}",
        if is_release_tag { "true" } else { "false" }
    );

    let is_official_release = is_official_release_build();
    println!(
        "cargo:rustc-env=FLOWSURFACE_IS_OFFICIAL_RELEASE={}",
        if is_official_release { "true" } else { "false" }
    );
}

fn generate_core_source_manifest() -> Result<(), String> {
    let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let core_dir = manifest_dir.join("indicators/core");
    println!("cargo:rerun-if-changed=indicators/core");

    let mut source_files = Vec::new();
    for entry in fs::read_dir(&core_dir).map_err(|error| {
        format!(
            "{}: could not read core indicators: {error}",
            core_dir.display()
        )
    })? {
        let entry = entry.map_err(|error| {
            format!(
                "{}: could not inspect core indicator entry: {error}",
                core_dir.display()
            )
        })?;
        let path = entry.path();
        if entry
            .file_type()
            .map_err(|error| format!("{}: could not inspect entry: {error}", path.display()))?
            .is_file()
            && path.extension().and_then(|extension| extension.to_str()) == Some("ind")
        {
            source_files.push(path);
        }
    }
    source_files.sort();

    if source_files.is_empty() {
        return Err(format!(
            "{} contains no core indicator .ind sources",
            core_dir.display()
        ));
    }

    let out_dir = env::var_os("OUT_DIR").expect("Cargo should provide OUT_DIR");
    let destination = PathBuf::from(out_dir).join("indicator_core_sources.rs");
    let mut generated = String::from(
        "// Generated by build.rs; edit the source files under indicators/core instead.\n\n",
    );
    generated.push_str("const CORE_SOURCES: &[CoreSource] = &[\n");

    for path in source_files {
        let file_name = path
            .file_name()
            .and_then(|name| name.to_str())
            .ok_or_else(|| {
                format!(
                    "{}: core source filename is not valid UTF-8",
                    path.display()
                )
            })?;
        let include_path = format!("/indicators/core/{file_name}");
        println!("cargo:rerun-if-changed={}", path.display());
        generated.push_str(&format!(
            "    CoreSource {{\n        file_name: {file_name:?},\n        source: include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {include_path:?})),\n    }},\n"
        ));
    }

    generated.push_str("];\n");
    fs::write(&destination, generated).map_err(|error| {
        format!(
            "could not generate core indicator source manifest {}: {error}",
            destination.display()
        )
    })
}

fn is_official_release_build() -> bool {
    if !env_var_is_truthy("FLOWSURFACE_OFFICIAL_RELEASE") {
        return false;
    }

    if !env_var_is_truthy("GITHUB_ACTIONS") {
        return false;
    }

    let workflow = env::var("GITHUB_WORKFLOW").unwrap_or_default();
    let event = env::var("GITHUB_EVENT_NAME").unwrap_or_default();

    workflow == "Release" && event == "workflow_dispatch"
}

fn env_var_is_truthy(name: &str) -> bool {
    let Ok(value) = env::var(name) else {
        return false;
    };

    value == "1"
        || value.eq_ignore_ascii_case("true")
        || value.eq_ignore_ascii_case("yes")
        || value.eq_ignore_ascii_case("on")
}

fn git_output(args: &[&str]) -> Option<String> {
    let output = Command::new("git").args(args).output().ok()?;
    if !output.status.success() {
        return None;
    }

    let stdout = String::from_utf8(output.stdout).ok()?;
    let value = stdout.trim().to_string();
    if value.is_empty() { None } else { Some(value) }
}

fn git_head_has_release_tag(pkg_version: &str) -> bool {
    let Some(tags) = git_output(&["tag", "--points-at", "HEAD"]) else {
        return false;
    };

    let prefixed = format!("v{pkg_version}");
    tags.lines().any(|tag| {
        let value = tag.trim();
        value == pkg_version || value == prefixed
    })
}
